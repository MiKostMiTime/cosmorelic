"""Streamlit UI for CosmoRelic (SRS §6). All logic lives in core.py."""

import streamlit as st

import core
import cosmorelic_data as data

FOOTER = (
    "AI-generated storytelling grounded in open NASA datasets. "
    "Not affiliated with or endorsed by NASA."
)

SOURCE_LIST = """\
**MEASURED** - a value recorded by an instrument or a published survey.

**EPHEMERIS** - a live position or distance computed by JPL Horizons.

**DERIVED** - arithmetic performed on a measured or ephemeris value.

**ARCHIVAL** - a fact from the mission record, not a live measurement.

**Data sources**
- JPL Horizons System - live Earth-Moon and Earth-Mars distance (`ssd.jpl.nasa.gov/horizons/`)
- NSSDCA - mission records and Apollo landing site coordinates (`nssdc.gsfc.nasa.gov`)
- NASA GISS Mars24 - Mars landing site coordinates (`giss.nasa.gov`)
- NASA Image and Video Library - archival photography (`images.nasa.gov`)
- NASA Science mission pages - Viking 1, Mars Pathfinder, Spirit and Opportunity, InSight, LROC

Every relic card lists the specific source for each number. Nothing on the card
is generated by the AI.
"""


def _start_chat(relic_key, offline):
    """Reset the conversation to the relic's opening monologue."""
    relic = core.get_relic(relic_key)
    st.session_state.relic_key = relic_key
    st.session_state.offline = offline
    st.session_state.messages = [
        {"role": "assistant", "content": core.first_transmission(relic)}
    ]


def _ensure_state(relic_key, offline):
    """Start a chat on first load, or when the relic or the mode changed."""
    if (
        "messages" not in st.session_state
        or st.session_state.get("relic_key") != relic_key
        or st.session_state.get("offline") != offline
    ):
        _start_chat(relic_key, offline)


def _ask(relic_key, question, offline):
    """Append the user's turn and the relic's reply to the session history."""
    question = (question or "").strip()
    if not question:
        return

    # Hand the model only the dialogue, not the opening monologue.
    prior = list(st.session_state.messages[1:])
    answer = core.reply(relic_key, question, prior, offline=offline)
    st.session_state.messages.append({"role": "user", "content": question})
    st.session_state.messages.append({"role": "assistant", "content": answer})


def main():
    st.set_page_config(page_title="CosmoRelic", layout="wide")

    st.title("CosmoRelic")
    st.subheader("Abandoned, but not forgotten.")
    st.markdown(
        "Eight machines were left behind on the Moon and Mars. Choose one and it will "
        "tell you its story - with every number labelled by how we know it."
    )

    choices = core.relic_choices()
    labels = [label for label, _ in choices]
    keys = [key for _, key in choices]
    default_index = keys.index("opportunity") if "opportunity" in keys else 0

    with st.sidebar:
        st.header("Choose a relic")
        picked = st.selectbox("Relic", labels, index=default_index)
        relic_key = keys[labels.index(picked)]
        offline = st.checkbox(
            "Low-power mode (no network - answer from archived memory)",
            value=False,
        )
        if st.button("Restart this conversation"):
            _start_chat(relic_key, offline)
            st.rerun()
        st.caption("Every number on the data card is labelled by how we know it.")

    _ensure_state(relic_key, offline)
    relic = core.get_relic(relic_key)

    left, right = st.columns(2, gap="large")

    with left:
        st.markdown(f"### {relic['name']}")
        st.caption(f"{relic['type']} - {relic['site']}, {relic['body']}")
        st.image(relic["image_url"])
        st.caption(f"{relic['image_title']} - {relic['image_credit']}")
        with st.spinner("Reading the live data card..."):
            cards = core.build_telemetry(relic, offline=offline)
        st.markdown(core.telemetry_to_markdown(cards, relic.get("agency_note", "")))
        st.markdown(
            f"[Open {relic['body']} Trek to explore the surface]({relic['trek_url']})"
        )

    with right:
        st.markdown("#### Ask the Relic - AI-generated stories")

        history_box = st.container(height=430)
        with history_box:
            for message in st.session_state.messages:
                with st.chat_message(message["role"]):
                    st.markdown(message["content"])

        with st.form("ask-the-relic", clear_on_submit=True):
            typed = st.text_input(
                "Your question",
                placeholder="Did you really say your battery was low?",
            )
            send = st.form_submit_button("Send")

        st.caption("Suggested questions")
        clicked = None
        for index, prompt in enumerate(relic["suggested_questions"][:3]):
            if st.button(prompt, key=f"suggested-{index}"):
                clicked = prompt

        st.caption(
            "AI-generated fiction grounded in cited data. The relic will tell you "
            "when it does not know something."
        )

        question = typed if (send and typed.strip()) else clicked
        if question:
            with st.spinner("The relic is recalling..."):
                _ask(relic_key, question, offline)
            st.rerun()

    with st.expander("Data & Sources"):
        st.markdown(SOURCE_LIST)

    with st.expander("For Teachers"):
        st.markdown(data.TEACHER_BOX)

    st.divider()
    st.caption(FOOTER)


main()
