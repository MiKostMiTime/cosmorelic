def load_relic(relic_key):
    """Populate the image, card, chat and suggested questions when a relic is chosen."""
    relic = core.get_relic(relic_key)
    cards = core.build_telemetry(relic)
    card_md = core.telemetry_to_markdown(cards, relic.get("agency_note", ""))
    chat = [{"role": "assistant", "content": core.first_transmission(relic)}]
    trek = (
        f"<a href='{relic['trek_url']}' target='_blank' rel='noopener'>"
        f"Open {relic['body']} Trek to explore the surface &rarr;</a>"
    )
    questions = list(relic["suggested_questions"])
    buttons = [gr.update(value=q, visible=True) for q in questions]
    return (
        f"### {relic['name']}\n*{relic['type']} - {relic['site']}, {relic['body']}*",
        relic["image_url"],
        f"{relic['image_title']} - {relic['image_credit']}",
        card_md,
        trek,
        chat,
        questions,
        buttons[0],
        buttons[1],
        buttons[2],
    )


def send_message(relic_key, question, history, offline):
    """Append the user's turn and the relic's reply."""
    history = list(history or [])
    if not (question or "").strip():
        return history, ""

    # Hand the model only the dialogue, not the opening monologue.
    dialogue = [t for t in history if isinstance(t, dict)]
    prior = dialogue[1:] if dialogue and dialogue[0]["role"] == "assistant" else dialogue

    answer = core.reply(relic_key, question, prior, offline=offline)
    history = history + [
        {"role": "user", "content": question},
        {"role": "assistant", "content": answer},
    ]
    return history, ""


def pick_question(questions, index, relic_key, history, offline):
    """A suggested-question button sends that question immediately."""
    if not questions or index >= len(questions):
        return history, ""
    return send_message(relic_key, questions[index], history, offline)


with gr.Blocks(title="CosmoRelic") as demo:
    gr.Markdown(
        "# CosmoRelic\n"
        "### Abandoned, but not forgotten.\n"
        "Eight machines were left behind on the Moon and Mars. Choose one and it will "
        "tell you its story - with every number labelled by how we know it."
    )

    with gr.Row():
        relic_dropdown = gr.Dropdown(
            choices=core.relic_choices(),
            value="opportunity",
            label="Choose a relic",
            scale=3,
        )
        load_btn = gr.Button("Load", variant="primary", scale=1)
    offline_toggle = gr.Checkbox(
        label="Low-power mode (no network - answer from archived memory)",
        value=False,
    )

    questions_state = gr.State([])

    with gr.Row():
        with gr.Column(scale=1):
            relic_title = gr.Markdown()
            relic_image = gr.Image(label="Archival photograph", height=260)
            image_caption = gr.Markdown()
            telemetry_card = gr.Markdown()
            trek_link = gr.HTML()

        with gr.Column(scale=1):
            chatbot = gr.Chatbot(
                label="Ask the Relic - AI-generated stories",
                height=420,
            )
            question_box = gr.Textbox(
                label="Your question",
                placeholder="Did you really say your battery was low?",
                lines=2,
            )
            send_btn = gr.Button("Send", variant="primary")
            with gr.Row():
                q1 = gr.Button("", size="sm", visible=False)
                q2 = gr.Button("", size="sm", visible=False)
                q3 = gr.Button("", size="sm", visible=False)
            gr.Markdown(
                "*AI-generated fiction grounded in cited data. The relic will tell you "
                "when it does not know something.*"
            )

    with gr.Accordion("Data & Sources", open=False):
        gr.Markdown(SOURCE_LIST)

    with gr.Accordion("For Teachers", open=False):
        gr.Markdown(data.TEACHER_BOX)

    gr.Markdown(f"---\n*{FOOTER}*")

    load_outputs = [
        relic_title,
        relic_image,
        image_caption,
        telemetry_card,
        trek_link,
        chatbot,
        questions_state,
        q1,
        q2,
        q3,
    ]
    load_btn.click(load_relic, inputs=[relic_dropdown], outputs=load_outputs)
    relic_dropdown.change(load_relic, inputs=[relic_dropdown], outputs=load_outputs)
    demo.load(load_relic, inputs=[relic_dropdown], outputs=load_outputs)

    send_btn.click(
        send_message,
        inputs=[relic_dropdown, question_box, chatbot, offline_toggle],
        outputs=[chatbot, question_box],
    )
    question_box.submit(
        send_message,
        inputs=[relic_dropdown, question_box, chatbot, offline_toggle],
        outputs=[chatbot, question_box],
    )
    for index, button in enumerate((q1, q2, q3)):
        button.click(
            lambda qs, k, h, off, i=index: pick_question(qs, i, k, h, off),
            inputs=[questions_state, relic_dropdown, chatbot, offline_toggle],
            outputs=[chatbot, question_box],
        )


if __name__ == "__main__":
    demo.launch(theme=gr.themes.Soft())